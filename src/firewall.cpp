// ----------------------------------------------------------------------------- nftables

static void nft_set(std::ostringstream& o, const char* name, const char* type,
                    const std::vector<std::string>& elems) {
    o << "    set " << name << " {\n        type " << type << "\n        flags interval\n";
    o << "        auto-merge\n";
    if (!elems.empty()) {
        o << "        elements = {\n";
        for (size_t i = 0; i < elems.size(); ++i)
            o << "            " << elems[i] << (i + 1 < elems.size() ? ",\n" : "\n");
        o << "        }\n";
    }
    o << "    }\n";
}

std::string generate_nft(const RuleSet& rs) {
    const SecurityConfig& s = rs.sec;
    std::ostringstream o;
    o << "#!/usr/sbin/nft -f\n"
         "# Generated by Varta - do not edit, run `varta apply` instead.\n"
         "# Idiom below: create the table if missing, delete it, then recreate atomically.\n"
         "table inet varta\n"
         "delete table inet varta\n\n"
         "table inet varta {\n";
    nft_set(o, "block4", "ipv4_addr", rs.ipv4);
    nft_set(o, "block6", "ipv6_addr", rs.ipv6);
    if (s.block_public_doh) {
        nft_set(o, "doh4", "ipv4_addr", doh_v4());
        nft_set(o, "doh6", "ipv6_addr", doh_v6());
    }
    if (s.block_smb_to_internet) {
        nft_set(o, "private4", "ipv4_addr", {std::begin(kPrivateV4), std::end(kPrivateV4)});
        nft_set(o, "private6", "ipv6_addr", {std::begin(kPrivateV6), std::end(kPrivateV6)});
    }

    // ---- inbound
    o << "\n    chain input {\n"
         "        type filter hook input priority 0; policy accept;\n"
         "        iifname \"lo\" accept\n"
         "        ct state established,related accept\n"
         "        ct state invalid drop\n"
         "        udp sport 67 udp dport 68 accept comment \"DHCPv4 replies\"\n"
         "        udp sport 547 udp dport 546 accept comment \"DHCPv6 replies\"\n";
    if (s.block_ping) {
        o << "        icmp type echo-request drop\n"
             "        icmpv6 type echo-request drop\n";
    }
    o << "        meta l4proto ipv6-icmp accept comment \"IPv6 neighbour discovery\"\n";
    if (!s.block_ping) o << "        icmp type echo-request accept\n";

    const Ports bl = blocked_inbound(s);
    if (!bl.tcp.empty()) o << "        tcp dport { " << list_of(bl.tcp, ", ") << " } counter drop\n";
    if (!bl.udp.empty()) o << "        udp dport { " << list_of(bl.udp, ", ") << " } counter drop\n";

    if (s.default_inbound_deny) {
        const Ports al = allowed_inbound(s);
        if (!al.tcp.empty()) o << "        tcp dport { " << list_of(al.tcp, ", ") << " } accept\n";
        if (!al.udp.empty()) o << "        udp dport { " << list_of(al.udp, ", ") << " } accept\n";
        if (rs.log) o << "        limit rate 10/second log prefix \"varta-in-drop: \"\n";
        o << "        counter drop comment \"default inbound deny\"\n";
    }
    o << "    }\n";

    // ---- outbound
    o << "\n    chain output {\n"
         "        type filter hook output priority 0; policy accept;\n"
         "        oifname \"lo\" accept\n";
    if (rs.log) {
        o << "        ip daddr @block4 limit rate 10/second log prefix \"varta-out: \"\n"
             "        ip6 daddr @block6 limit rate 10/second log prefix \"varta-out: \"\n";
    }
    o << "        ip daddr @block4 counter reject comment \"tracking/telemetry IPs\"\n"
         "        ip6 daddr @block6 counter reject comment \"tracking/telemetry IPs\"\n";
    if (s.block_public_doh) {
        o << "        ip daddr @doh4 meta l4proto { tcp, udp } th dport { 443, 853 } counter reject "
             "comment \"public DoH/DoT\"\n"
             "        ip6 daddr @doh6 meta l4proto { tcp, udp } th dport { 443, 853 } counter "
             "reject comment \"public DoH/DoT\"\n";
    }
    if (s.block_smb_to_internet) {
        o << "        ip daddr != @private4 tcp dport { 139, 445 } counter reject comment \"SMB to "
             "internet\"\n"
             "        ip6 daddr != @private6 tcp dport { 139, 445 } counter reject comment \"SMB "
             "to internet\"\n";
    }
    o << "    }\n}\n";
    return o.str();
}

// ----------------------------------------------------------------------------------- pf

std::string generate_pf(const RuleSet& rs) {
    const SecurityConfig& s = rs.sec;
    const std::string log = rs.log ? " log" : "";
    std::ostringstream o;
    o << "# Generated by Varta - loaded into anchor com.apple/varta. Do not edit.\n";

    std::vector<std::string> block = rs.ipv4;
    block.insert(block.end(), rs.ipv6.begin(), rs.ipv6.end());
    o << "table <varta_block> persist";
    if (!block.empty()) o << " { " << join(block, " ") << " }";
    o << "\n";
    if (s.block_public_doh) o << "table <varta_doh> const { " << join(public_doh_resolvers(), " ") << " }\n";
    if (s.block_smb_to_internet) {
        std::vector<std::string> priv(std::begin(kPrivateV4), std::end(kPrivateV4));
        priv.insert(priv.end(), std::begin(kPrivateV6), std::end(kPrivateV6));
        o << "table <varta_private> const { " << join(priv, " ") << " }\n";
    }

    o << "\npass quick on lo0 all\n";

    // ---- outbound
    o << "block return out" << log << " quick to <varta_block>\n";
    if (s.block_public_doh)
        o << "block return out" << log << " quick proto { tcp udp } to <varta_doh> port { 443 853 }\n";
    if (s.block_smb_to_internet)
        o << "block return out" << log << " quick proto tcp to ! <varta_private> port { 139 445 }\n";

    // ---- inbound
    o << "pass in quick proto udp from any port 67 to any port 68\n"
         "pass in quick proto udp from any port 547 to any port 546\n";
    if (s.block_ping) {
        o << "block drop in" << log << " quick inet proto icmp icmp-type echoreq\n"
          << "block drop in" << log << " quick inet6 proto ipv6-icmp icmp6-type echoreq\n";
    }
    o << "pass in quick inet6 proto ipv6-icmp all\n";
    if (!s.block_ping) o << "pass in quick inet proto icmp icmp-type echoreq\n";

    const Ports bl = blocked_inbound(s);
    if (!bl.tcp.empty())
        o << "block drop in" << log << " quick proto tcp to any port { " << list_of(bl.tcp, " ") << " }\n";
    if (!bl.udp.empty())
        o << "block drop in" << log << " quick proto udp to any port { " << list_of(bl.udp, " ") << " }\n";

    if (s.default_inbound_deny) {
        const Ports al = allowed_inbound(s);
        if (!al.tcp.empty()) o << "pass in quick proto tcp to any port { " << list_of(al.tcp, " ") << " }\n";
        if (!al.udp.empty()) o << "pass in quick proto udp to any port { " << list_of(al.udp, " ") << " }\n";
        o << "block drop in" << log << " quick all\n";
    }
    return o.str();
}

// --------------------------------------------------------------------------- PowerShell

static std::string ps_array(const std::vector<std::string>& v) {
    std::string out = "@(";
    for (size_t i = 0; i < v.size(); ++i) {
        if (i) out += ",";
        out += "'" + v[i] + "'";
    }
    return out + ")";
}

static void ps_rule(std::ostringstream& o, const std::string& name, const std::string& args) {
    o << "New-NetFirewallRule -Group $G -DisplayName 'Varta: " << name << "' " << args
      << " | Out-Null\n";
}

std::string generate_powershell_apply(const RuleSet& rs, bool diagtrack) {
    const SecurityConfig& s = rs.sec;
    std::ostringstream o;
    o << "# Generated by Varta - applies Windows Defender Firewall rules (group 'Varta').\n"
         "$ErrorActionPreference = 'Stop'\n"
         "$G = 'Varta'\n"
         "try {\n"
         "Remove-NetFirewallRule -Group $G -ErrorAction SilentlyContinue\n";

    // Outbound IP blocks, chunked to keep each rule a reasonable size.
    std::vector<std::string> ips = rs.ipv4;
    ips.insert(ips.end(), rs.ipv6.begin(), rs.ipv6.end());
    const size_t chunk = 500;
    for (size_t i = 0, n = 1; i < ips.size(); i += chunk, ++n) {
        std::vector<std::string> part(ips.begin() + static_cast<long>(i),
                                      ips.begin() + static_cast<long>(std::min(ips.size(), i + chunk)));
        ps_rule(o, "block tracking IPs #" + std::to_string(n),
                "-Direction Outbound -Action Block -RemoteAddress " + ps_array(part));
    }

    if (s.block_public_doh) {
        for (const char* proto : {"TCP", "UDP"})
            ps_rule(o, std::string("block public DoH/DoT ") + proto,
                    std::string("-Direction Outbound -Action Block -Protocol ") + proto +
                        " -RemotePort 443,853 -RemoteAddress " + ps_array(public_doh_resolvers()));
    }
    if (s.block_smb_to_internet) {
        ps_rule(o, "block SMB to internet",
                "-Direction Outbound -Action Block -Protocol TCP -RemotePort 139,445 -RemoteAddress " +
                    ps_array({std::begin(kPublicV4Ranges), std::end(kPublicV4Ranges)}));
    }

    if (s.block_ping) {
        ps_rule(o, "block inbound ping v4", "-Direction Inbound -Action Block -Protocol ICMPv4 -IcmpType 8");
        ps_rule(o, "block inbound ping v6", "-Direction Inbound -Action Block -Protocol ICMPv6 -IcmpType 128");
    }
    const Ports bl = blocked_inbound(s);
    if (!bl.tcp.empty())
        ps_rule(o, "block inbound TCP " + list_of(bl.tcp, ","),
                "-Direction Inbound -Action Block -Protocol TCP -LocalPort " + list_of(bl.tcp, ","));
    if (!bl.udp.empty())
        ps_rule(o, "block inbound UDP " + list_of(bl.udp, ","),
                "-Direction Inbound -Action Block -Protocol UDP -LocalPort " + list_of(bl.udp, ","));

    if (s.default_inbound_deny) {
        Ports al = allowed_inbound(s);
        // Windows: mDNS is handled by its own built-in rules; only open what the user asked for.
        if (!s.block_mdns) {
            al.udp.erase(std::remove(al.udp.begin(), al.udp.end(), 5353), al.udp.end());
        }
        if (!al.tcp.empty())
            ps_rule(o, "allow inbound TCP " + list_of(al.tcp, ","),
                    "-Direction Inbound -Action Allow -Protocol TCP -LocalPort " + list_of(al.tcp, ","));
        if (!al.udp.empty())
            ps_rule(o, "allow inbound UDP " + list_of(al.udp, ","),
                    "-Direction Inbound -Action Allow -Protocol UDP -LocalPort " + list_of(al.udp, ","));
        o << "Set-NetFirewallProfile -Profile Domain,Private,Public -Enabled True "
             "-DefaultInboundAction Block\n";
    }
    o << "Set-NetFirewallProfile -Profile Domain,Private,Public -LogBlocked "
      << (rs.log ? "True" : "False") << "\n";

    if (diagtrack) {
        o << "# Disable the 'Connected User Experiences and Telemetry' service\n"
             "Stop-Service -Name DiagTrack -Force -ErrorAction SilentlyContinue\n"
             "Set-Service -Name DiagTrack -StartupType Disabled\n"
             "$k = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\DataCollection'\n"
             "New-Item -Path $k -Force | Out-Null\n"
             "Set-ItemProperty -Path $k -Name AllowTelemetry -Type DWord -Value 0\n";
    }
    o << "} catch {\n"
         "  Write-Error $_\n"
         "  exit 1\n"
         "}\n"
         "exit 0\n";
    return o.str();
}

std::string generate_powershell_remove(bool restore_diagtrack) {
    std::ostringstream o;
    o << "# Generated by Varta - removes all Varta firewall rules.\n"
         "Remove-NetFirewallRule -Group 'Varta' -ErrorAction SilentlyContinue\n";
    if (restore_diagtrack) {
        o << "Set-Service -Name DiagTrack -StartupType Automatic -ErrorAction SilentlyContinue\n"
             "Start-Service -Name DiagTrack -ErrorAction SilentlyContinue\n"
             "Remove-ItemProperty -Path "
             "'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\DataCollection' -Name AllowTelemetry "
             "-ErrorAction SilentlyContinue\n";
    }
    o << "exit 0\n";
    return o.str();
}

std::string generate_firewall(Os os, const RuleSet& rs, bool diagtrack) {
    switch (os) {
        case Os::Linux: return generate_nft(rs);
        case Os::MacOS: return generate_pf(rs);
        case Os::Windows: return generate_powershell_apply(rs, diagtrack);
    }
    return {};
}

// ------------------------------------------------------------------------ apply / remove

static bool write_script(const std::string& dir, const std::string& name,
                         const std::string& content, std::string& path, std::string& err) {
    path = (fs::path(dir) / name).string();
    return write_file_atomic(path, content, err);
}

static std::string powershell(const std::string& script_path) {
    return "powershell -NoProfile -ExecutionPolicy Bypass -File " + shell_quote(script_path);
}

bool firewall_apply(const RuleSet& rs, const std::string& work_dir, bool diagtrack,
                    std::string& err) {
    std::string path;
    switch (current_os()) {
        case Os::Linux: {
            if (run("command -v nft", true) != 0) {
                err = "nft not found - install nftables (sudo apt install nftables)";
                return false;
            }
            if (!write_script(work_dir, "varta.nft", generate_nft(rs), path, err)) return false;
            if (run("nft -f " + shell_quote(path)) != 0) {
                err = "nft rejected the ruleset (see message above), file: " + path;
                return false;
            }
            return true;
        }
        case Os::MacOS: {
            if (!write_script(work_dir, "varta.pf", generate_pf(rs), path, err)) return false;
            if (run("pfctl -a com.apple/varta -f " + shell_quote(path), true) != 0) {
                err = "pfctl rejected the ruleset, check with: sudo pfctl -nvf " + path;
                return false;
            }
            run("pfctl -E", true);  // enable pf (no-op if already enabled)
            return true;
        }
        case Os::Windows: {
            if (!write_script(work_dir, "varta-apply.ps1", generate_powershell_apply(rs, diagtrack),
                              path, err))
                return false;
            if (run(powershell(path)) != 0) {
                err = "PowerShell failed to apply firewall rules, script: " + path;
                return false;
            }
            return true;
        }
    }
    return false;
}

bool firewall_remove(const std::string& work_dir, bool restore_diagtrack, std::string& err) {
    switch (current_os()) {
        case Os::Linux:
            if (run("nft list table inet varta", true) == 0 &&
                run("nft delete table inet varta") != 0) {
                err = "failed to delete nftables table inet varta";
                return false;
            }
            return true;
        case Os::MacOS:
            run("pfctl -a com.apple/varta -F all", true);
            return true;
        case Os::Windows: {
            std::string path;
            if (!write_script(work_dir, "varta-remove.ps1",
                              generate_powershell_remove(restore_diagtrack), path, err))
                return false;
            if (run(powershell(path)) != 0) {
                err = "PowerShell failed to remove Varta rules";
                return false;
            }
            return true;
        }
    }
    return false;
}

FirewallStatus firewall_status(bool verbose) {
    FirewallStatus st;
    int code = 0;
    switch (current_os()) {
        case Os::Linux: {
            const std::string out = run_capture("nft list table inet varta 2>/dev/null", code);
            st.active = code == 0 && !out.empty();
            st.details = st.active ? (verbose ? out : "nftables table 'inet varta' loaded")
                                   : "no nftables table 'inet varta'";
            break;
        }
        case Os::MacOS: {
            const std::string rules =
                run_capture("pfctl -a com.apple/varta -s rules 2>/dev/null", code);
            const std::string info = run_capture("pfctl -s info 2>/dev/null", code);
            const bool enabled = info.find("Status: Enabled") != std::string::npos;
            st.active = enabled && !trim(rules).empty();
            st.details = std::string("pf ") + (enabled ? "enabled" : "DISABLED") + ", anchor " +
                         (trim(rules).empty() ? "empty" : "loaded");
            if (verbose && !rules.empty()) st.details += "\n" + rules;
            break;
        }
        case Os::Windows: {
            const std::string out = run_capture(
                "powershell -NoProfile -Command \"Get-NetFirewallRule -Group 'Varta' "
                "-ErrorAction SilentlyContinue | ForEach-Object { $_.DisplayName }\"",
                code);
            const auto lines = split(trim(out), '\n');
            const size_t n = trim(out).empty() ? 0 : lines.size();
            st.active = n > 0;
            st.details = std::to_string(n) + " Windows Firewall rules in group 'Varta'";
            if (verbose && n) st.details += "\n" + out;
            break;
        }
    }
    return st;
}

